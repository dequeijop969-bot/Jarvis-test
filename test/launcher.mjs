// Abrir apps e sites por voz: entende o pedido, abre só o que é permitido, nunca passa texto do usuário para um shell.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { EventEmitter } from 'node:events';

const DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'jarvis-open-'));
const PORT = 3000 + Math.floor(Math.random() * 900) + 50;
Object.assign(process.env, { JARVIS_NO_LISTEN: '1', JARVIS_DATA_DIR: DIR, PORT: String(PORT), GEMINI_API_KEY: 'openTestGeminiKey-0000', ProgramFiles: 'C:\\PF' });

const L = await import('../lib/launcher.js');
const spawned = [];
const FAKE = new Set(['C:\\PF\\Google\\Chrome\\Application\\chrome.exe', 'C:\\Jogos\\Jogo.exe']);
L.OPEN.platform = 'win32';
L.OPEN.exists = p => FAKE.has(path.win32.normalize(p));
L.OPEN.spawn = (cmd, args, opt) => { spawned.push({ cmd: path.win32.normalize(cmd), args, shell: opt.shell }); const c = new EventEmitter(); c.unref = () => {}; return c; };
const { detectIntent } = await import('../lib/assistant.js');
const k = t => detectIntent(t)?.target;

// 1. Entende pedidos comuns
assert.equal(k('abre o chrome').key, 'chrome');
assert.equal(k('Jarvis, abre o YouTube por favor').url, 'https://www.youtube.com');
assert.equal(k('abre uma guia do g1 ponto com').url, 'https://g1.com');
assert.equal(k('abre uma nova guia').key, 'newtab');
assert.match(k('pesquisa no google receita de bolo').url, /google\.com\/search\?q=receita%20de%20bolo$/);
assert.equal(k('abre a calculadora').key, 'calculadora');
// Não é pedido de abrir (segue o caminho normal)
assert.equal(detectIntent('abre esse'), null);
assert.equal(detectIntent('abre minha agenda').kind, 'agenda');
assert.equal(detectIntent('pesquisa imagens de gatos').kind, 'images');
assert.equal(detectIntent('abre o rm -rf'), null);
assert.equal(detectIntent('abre o site evil.com" & calc'), null);
console.log('launcher: intenção ok');

// 2. Abrir: sem shell para sites; "start" só com nomes da lista fixa
await L.openTarget(k('abre o youtube'));
assert.deepEqual(spawned.at(-1), { cmd: 'C:\\PF\\Google\\Chrome\\Application\\chrome.exe', args: ['https://www.youtube.com'], shell: false });
await L.openTarget(k('abre a calculadora'));
assert.deepEqual(spawned.at(-1), { cmd: 'cmd.exe', args: ['/d', '/c', 'start', '', 'calc'], shell: false });
await assert.rejects(L.openTarget({ type: 'url', url: 'javascript:alert(1)' }), /inválido/);
await assert.rejects(L.openTarget({ type: 'url', url: 'https://x.com" & calc' }), /inválido/);
await assert.rejects(L.openTarget({ type: 'app', key: 'powershell' }), /Não conheço/);
console.log('launcher: abrir ok');

// 3. Apps cadastrados: só .exe/.lnk existentes, caminho absoluto
assert.throws(() => L.addApp('xx', 'C:\\Jogos\\nada.exe'), /Não encontrei/);
assert.throws(() => L.addApp('script', 'C:\\Jogos\\a.bat'), /\.exe/);
assert.throws(() => L.addApp('rel', 'Jogo.exe'), /caminho completo/);
L.addApp('Meu Jogo', '"C:\\Jogos\\Jogo.exe"');
assert.deepEqual(k('abre o meu jogo'), { type: 'custom', key: 'meu jogo', label: 'meu jogo', path: 'C:\\Jogos\\Jogo.exe' });
await L.openTarget(k('abre o meu jogo'));
assert.deepEqual(spawned.at(-1), { cmd: 'explorer.exe', args: ['C:\\Jogos\\Jogo.exe'], shell: false });
console.log('launcher: apps cadastrados ok');

// Apps instalados (lista do menu Iniciar): acha pelo nome, sem cadastro; ignora desinstalador, suporte e links.
L.OPEN.listApps = async () => [
  { name: 'OBS Studio', id: '{6D809377}\\obs-studio\\bin\\64bit\\obs64.exe' }, { name: 'Uninstall OBS Studio', id: 'Microsoft.AutoGenerated.{A1}' },
  { name: 'VALORANT', id: 'Riot Game valorant.live' }, { name: 'Discord', id: 'com.squirrel.Discord.Discord' },
  { name: 'Steam Support Center', id: 'http://support.steampowered.com/' }, { name: 'WhatsApp', id: '5319275A.WhatsAppDesktop_cv1g1gvanyjgm!App' },
  { name: 'Microsoft Teams', id: 'MSTeams_8wekyb3d8bbwe!MSTeams' }];
await L.refreshInstalled(true);
assert.equal(L.installedApps().length, 5, 'sem o desinstalador e sem o link');
const inst = t => { const o = L.parseOpen(t); return o?.type === 'installed' ? o.label : o?.type || null; };
assert.equal(inst('abre o obs'), 'OBS Studio');
assert.equal(inst('abre o obs studio'), 'OBS Studio');
assert.equal(inst('abre o jogo valorant'), 'VALORANT');
assert.equal(inst('abre o discord'), 'app', 'o Discord já está na lista fixa');
assert.equal(inst('abre o teams'), 'Microsoft Teams');
assert.equal(inst('abre o whatsapp'), 'url', 'whatsapp continua indo para o site, como antes');
assert.equal(inst('abre o youtube'), 'url', 'sites conhecidos vêm antes');
assert.equal(inst('abre o chrome'), 'app', 'apps da lista fixa vêm antes');
assert.equal(L.parseOpen('abre o photoshop'), null, 'não instalado: nada');
spawned.length = 0;
await L.openTarget(L.parseOpen('abre o obs'));
assert.equal(spawned[0].cmd, 'explorer.exe'); assert.deepEqual(spawned[0].args, ['shell:AppsFolder\\{6D809377}\\obs-studio\\bin\\64bit\\obs64.exe']);
await assert.rejects(L.openTarget({ type: 'installed', key: 'calc.exe" & del', label: 'x' }), /Não encontrei/, 'só IDs da lista do Windows');
console.log('launcher: apps instalados (sem cadastro) ok');

// 4. Pelo servidor (voz → /api/chat), e o interruptor desliga
const { server } = await import('../server.js');
const { saveProfile } = await import('../lib/profile.js');
saveProfile({ name: 'Teste', address: 'senhor', lang: 'pt-BR', city: { name: 'Jundiaí', latitude: -23.2, longitude: -46.9, timezone: 'America/Sao_Paulo' } }, null);
await new Promise(r => server.listen(PORT, '127.0.0.1', r));
const chat = async text => (await (await fetch(`http://localhost:${PORT}/api/chat`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-jarvis': '1' }, body: JSON.stringify({ text }) })).json());
try {
  const n = spawned.length;
  let j = await chat('abre o youtube');
  assert.match(j.intro, /Abrindo o YouTube no navegador, senhor/); assert.equal(j.opened.url, 'https://www.youtube.com'); assert.equal(spawned.length, n + 1);
  saveProfile({ launcher: false });
  j = await chat('abre o youtube');
  assert.match(j.intro, /desligado/); assert.equal(spawned.length, n + 1, 'desligado: nada é aberto');
  const st = await (await fetch(`http://localhost:${PORT}/api/state`)).json();
  assert.equal(st.profile.launcher, false); assert.equal(st.integrations.launcher.apps[0].name, 'meu jogo');
  const r = await fetch(`http://localhost:${PORT}/api/apps`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
  assert.equal(r.status, 403, 'cadastrar app exige x-jarvis');
  console.log('launcher: servidor ok');
} finally { server.close(); }
