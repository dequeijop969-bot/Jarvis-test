// Skills e agenda local: gatilhos, limpeza e a sequência de passos rodando pelo /api/chat.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'skills-'));
Object.assign(process.env, { JARVIS_NO_LISTEN: '1', JARVIS_DATA_DIR: DIR, PORT: '3091' });
const sk = await import('../lib/skills.js');
const a = sk.upsert({ name: 'Modo trabalho', triggers: 'modo trabalho, hora de trabalhar', steps: 'abre a calculadora\nabre o bloco de notas' });
assert.equal(a.steps.length, 2); assert.deepEqual(a.triggers, ['modo trabalho', 'hora de trabalhar']);
assert.equal(sk.match('Jarvis, modo trabalho')?.id, a.id);
assert.equal(sk.match('hora de trabalhar por favor')?.id, a.id);
assert.equal(sk.match('executa a skill modo trabalho')?.id, a.id);
assert.equal(sk.match('roda a rotina trabalho')?.id, a.id, '"rotina trabalho" casa com "modo trabalho"');
assert.equal(sk.match('qual o modo de trabalho ideal?'), null, 'pergunta comum não dispara');
assert.throws(() => sk.upsert({ name: 'x', steps: '' }), /pelo menos um passo/);
assert.equal(sk.clean({ name: 'y', steps: Array(20).fill('passo') }).steps.length, 10);
const lc = await import('../lib/localcal.js');
const e = lc.add({ title: '  Dentista <b>  ', start: Date.UTC(2030, 0, 2, 15) });
assert.equal(e.title, 'Dentista b'); assert.equal(e.end - e.start, 3600e3, 'sem fim: uma hora');
assert.equal(lc.between(Date.UTC(2030, 0, 2), Date.UTC(2030, 0, 3)).length, 1);
assert.ok(lc.remove(e.id)); assert.equal(lc.between(0, Date.UTC(2100, 0, 1)).length, 0);
assert.throws(() => lc.add({ title: '', start: Date.now() }), /nome/);
console.log('skills: gatilhos, limites e agenda local ok');
process.exit(0);
